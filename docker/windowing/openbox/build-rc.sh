#!/bin/bash
# build-rc.sh - regenerate this package's self-contained openbox rc.xml.
#
# Everything it reads lives in this directory, so the layer is hermetic:
#   stock-3.6.1.rc.xml.reference  skeleton = the openbox 3.6.1 stock rc the base
#                                 image ships (reference copy; provenance:
#                                 script/webtop-image/windowing/openbox/)
#   merge-rc.py                   merger/validator (same provenance)
#   overlays.keyboard.xml         added keybindings (A-F9 / A-F10 / A-S-F9 / A-F3)
#   overlays.applications.xml     decor + placement rules
#
# merge-rc.py also, and this script depends on it doing so:
#   * drops the wildcard decor=no / maximized=yes injections (the untitled-bar
#     and 2026-10-15 black-screen root causes from the previous webtop package),
#   * forces dock = Bottom + Horizontal (tint2's panel_position alone is not
#     enough: with a Vertical dock two docked panels stack at the top),
#   * forces theme/titleLayout = NLIMC (stock 3.6.1 ships NLMC, where L is the
#     label and not an iconify button => titlebars render without minimize),
#   * validates structure + rule ordering and refuses to write a failing file.
# Output is self-contained: no <include>, no dependency on /etc/xdg.
#
# Usage (from anywhere):
#   bash script/webtop-kasmvnc/image/windowing/openbox/build-rc.sh
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
OUT="$HERE/rc.xml"
TMP="$HERE/.rc.xml.merging.$$"
STOCK="$HERE/stock-3.6.1.rc.xml.reference"
MERGER="$HERE/merge-rc.py"
KB="$HERE/overlays.keyboard.xml"
AP="$HERE/overlays.applications.xml"

for f in "$STOCK" "$MERGER" "$KB" "$AP"; do
  [ -r "$f" ] || { echo "build-rc: missing input $f" >&2; exit 2; }
done

python3 "$MERGER" "$STOCK" "$TMP" "$KB" "$AP"

# Ownership marker: the merger stamps the wdev marker (it is the shared tool of
# the previous package); rewrite it to this package's marker so an init script
# can tell "generated by us" from "hand-written by the user" and never clobber
# the latter.
python3 - "$TMP" <<'PYEOF'
import sys
p = sys.argv[1]
s = open(p, encoding="utf-8").read()
OLD = '  <!-- wdev-windowing:generated (do not edit by hand; regenerate via wdev-windowing-init.sh) -->'
NEW = ('  <!-- wtk-windowing:generated  (do not hand-edit; regenerate via build-rc.sh)\n'
       '       Base = openbox 3.6.1 stock rc; overlays = the keyboard and\n'
       '       applications fragments in this directory. Self-contained: no <include>. -->')
if OLD not in s:
    sys.exit('build-rc: merge marker not found (merge-rc.py changed?)')
s = s.replace(OLD, NEW, 1)
open(p, 'w', encoding='utf-8').write(s)
PYEOF

python3 -c 'import xml.dom.minidom,sys; xml.dom.minidom.parse(sys.argv[1])' "$TMP"
mv -f "$TMP" "$OUT"
echo "build-rc: wrote $OUT ($(wc -c < "$OUT") bytes)"

